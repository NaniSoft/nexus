/**
 * Pre-bakes antd's theme variables for this site's pack in both modes —
 * prism-ui's library-owned flash-free recipe (ADR-0006 §4), consumed via
 * bakePrismThemeCss from the published package. Emits app/antd-vars.css; the
 * blocking boot script (lib/theme.ts) swaps the class on <html> pre-paint.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.NODE_ENV = 'production'; // antd's dev-only deprecation warnings would otherwise pollute the bake

import { bakePrismThemeCss } from '@nanisoft/prism-ui/theming';

const OUT_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'antd-vars.css');

const css = bakePrismThemeCss({ pack: 'lavender' });

await mkdir(path.dirname(OUT_FILE), { recursive: true });
await writeFile(
  OUT_FILE,
  [
    '/* GENERATED by scripts/bake-antd-css.mjs — do not edit.',
    '   One pre-baked antd variable ruleset per mode for the lavender pack,',
    '   keyed by the prism-lavender-<mode> cssVar class. */',
    '',
    css,
    '',
  ].join('\n'),
);
console.log('bake-antd-css: wrote ' + path.relative(process.cwd(), OUT_FILE) + ' (' + css.length + ' bytes)');
